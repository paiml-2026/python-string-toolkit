def compare_text_lengths(text1, text2):
    # Find the length of both strings
    length1 = len(text1)
    length2 = len(text2)

    # Compare the lengths
    if length1 > length2:
        return "first"
    elif length2 > length1:
        return "second"
    else:
        return "equal"


# Test cases
print(compare_text_lengths("hello", "Python"))
print(compare_text_lengths("Programming", "Code"))
print(compare_text_lengths("Hello", "World"))